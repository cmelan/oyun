let lang: Lang = 'tr';
export function setLang(l: Lang): void { lang = l; }
export function getLang(): Lang { return lang; }

export function S(key: string): string {
  const t = STR[lang];
  if (t && t[key] !== undefined) return t[key];
  return STR.tr[key] !== undefined ? STR.tr[key] : key;
}

