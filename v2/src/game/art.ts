/* Card & journal art: real photos when present (TREES[id].photos — the mandated
   final art), botanically-shaped vector fallback otherwise. The 13 v1 leaf paths
   are ported verbatim (all verified at 58px in v1); the 13 v2 paths await the
   combined photo/58px pass. Silhouette tier renders the same path in dark fill. */
import { TREES } from '../core/trees';
import { PHOTOS } from '../core/photos.generated';

/* Real photos take precedence over TREES[id].photos (owner-supplied) and both
   over vector art. Fetched photos live in PHOTOS (generated by fetch-photos.mjs). */
function photoFor(id: string): { leaf?: string; bark?: string; tree?: string } | undefined {
  return PHOTOS[id] || TREES[id]?.photos;
}

type Ctx = CanvasRenderingContext2D;
type PathFn = (c: Ctx, cx: number, cy: number, s: number) => void;

/* ---------- v1 paths (verbatim) ---------- */
function pathOakLeaf(c: Ctx, cx: number, cy: number, s: number) {
  const lobes = 3;
  c.beginPath(); c.moveTo(cx, cy - .44 * s);
  for (let i = 0; i < lobes; i++) { const y1 = cy - .44 * s + ((i + .5) / lobes) * .80 * s, y2 = cy - .44 * s + ((i + 1) / lobes) * .80 * s, bulge = .40 * s - i * .03 * s; c.quadraticCurveTo(cx + bulge, y1 - .02 * s, cx + .13 * s, y2); }
  c.lineTo(cx + .06 * s, cy + .42 * s); c.lineTo(cx, cy + .5 * s); c.lineTo(cx - .06 * s, cy + .42 * s);
  for (let i = lobes - 1; i >= 0; i--) { const y2 = cy - .44 * s + (i / lobes) * .80 * s, y1 = cy - .44 * s + ((i + .5) / lobes) * .80 * s, bulge = .40 * s - i * .03 * s; c.quadraticCurveTo(cx - bulge, y1 - .02 * s, cx - .13 * s, y2); }
  c.closePath();
}
