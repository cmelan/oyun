function quadSample(base: number[][], p0: number[], cp: number[], p1: number[], n: number) {
  for (let i = 1; i <= n; i++) { const tt = i / n, x = (1 - tt) * (1 - tt) * p0[0] + 2 * (1 - tt) * tt * cp[0] + tt * tt * p1[0], y = (1 - tt) * (1 - tt) * p0[1] + 2 * (1 - tt) * tt * cp[1] + tt * tt * p1[1]; base.push([x, y]); }
}
function pathBirchLeaf(c: Ctx, cx: number, cy: number, s: number) {
  const base: number[][] = [];
  let cur = [cx, cy - .44 * s]; base.push(cur);
  const steps = [[[cx + .26 * s, cy - .22 * s], [cx + .28 * s, cy + .04 * s]], [[cx + .26 * s, cy + .26 * s], [cx + .08 * s, cy + .36 * s]], [[cx, cy + .4 * s], [cx, cy + .42 * s]],
    [[cx, cy + .4 * s], [cx - .08 * s, cy + .36 * s]], [[cx - .26 * s, cy + .26 * s], [cx - .28 * s, cy + .04 * s]], [[cx - .26 * s, cy - .22 * s], [cx, cy - .44 * s]]];
  for (const st of steps) { quadSample(base, cur, st[0], st[1], 10); cur = st[1]; }
  c.beginPath();
  base.forEach((p, i) => { const dx = p[0] - cx, dy = p[1] - cy, d = Math.hypot(dx, dy) || 1, tooth = 1 + ((i % 3 === 0) ? .045 : 0); const x = cx + dx / d * d * tooth, y = cy + dy / d * d * tooth; if (i === 0) c.moveTo(x, y); else c.lineTo(x, y); });
  c.closePath();
}
function pathMapleLeaf(c: Ctx, cx: number, cy: number, s: number) {
  const n = 5, tipR = .5, valleyR = .2;
  c.beginPath();
  for (let i = 0; i < n; i++) {
    const aTip = -Math.PI / 2 + i * (2 * Math.PI / n), aPrevV = aTip - Math.PI / n, aNextV = aTip + Math.PI / n;
    const pv = [cx + Math.cos(aPrevV) * valleyR * s, cy + Math.sin(aPrevV) * valleyR * s];
    const tip = [cx + Math.cos(aTip) * tipR * s, cy + Math.sin(aTip) * tipR * s];
    const nv = [cx + Math.cos(aNextV) * valleyR * s, cy + Math.sin(aNextV) * valleyR * s];
    const cp1 = [cx + Math.cos((aPrevV + aTip) / 2) * tipR * s * .7, cy + Math.sin((aPrevV + aTip) / 2) * tipR * s * .7];
    const cp2 = [cx + Math.cos((aTip + aNextV) / 2) * tipR * s * .7, cy + Math.sin((aTip + aNextV) / 2) * tipR * s * .7];
    if (i === 0) c.moveTo(pv[0], pv[1]);
    c.quadraticCurveTo(cp1[0], cp1[1], tip[0], tip[1]); c.quadraticCurveTo(cp2[0], cp2[1], nv[0], nv[1]);
  }
  c.closePath();
}
