const iconCache: Record<string, string> = {};

/* Vector leaf icon (gradient fill + veins + stem, optional bark strip) — v1 port. */
export function getTreeIcon(species: string, size: number, withBark = true): string {
  const key = `${species}:${size}:${withBark}`;
  if (iconCache[key]) return iconCache[key];
  const cv = document.createElement('canvas');
  cv.width = size; cv.height = Math.round(withBark ? size * 1.32 : size * 1.08);
  const c = cv.getContext('2d')!;
  const cx = size / 2, cy = size * .46, s = size * .86;
  const pathFn = LEAF_PATH[species] || LEAF_PATH['meşe'];
  const cols = LEAF_COLOR[species] || LEAF_COLOR['meşe'];
  c.strokeStyle = '#6b5a3a'; c.lineWidth = Math.max(1.6, size * .03); c.lineCap = 'round';
  c.beginPath(); c.moveTo(cx, cy + .42 * s); c.quadraticCurveTo(cx + .03 * s, cy + .5 * s, cx - .02 * s, cy + .56 * s); c.stroke();
  pathFn(c, cx, cy, s);
  const lg = c.createLinearGradient(cx - .4 * s, cy - .4 * s, cx + .4 * s, cy + .4 * s);
  lg.addColorStop(0, cols[0]); lg.addColorStop(1, cols[1]);
  c.fillStyle = lg; c.fill();
  c.strokeStyle = 'rgba(20,50,35,.45)'; c.lineWidth = Math.max(1.1, size * .018); c.stroke();
  c.save(); pathFn(c, cx, cy, s); c.clip();
  c.strokeStyle = 'rgba(255,255,255,.5)'; c.lineWidth = Math.max(1, size * .016); c.lineCap = 'round';
  c.beginPath(); c.moveTo(cx, cy - .42 * s); c.lineTo(cx, cy + .42 * s); c.stroke();
  c.lineWidth = Math.max(.8, size * .011);
  for (let i = 0; i < 4; i++) {
    const vy = cy - .30 * s + i * .19 * s;
    c.beginPath(); c.moveTo(cx, vy); c.quadraticCurveTo(cx + .16 * s, vy + .02 * s, cx + .30 * s, vy - .07 * s); c.stroke();
    c.beginPath(); c.moveTo(cx, vy); c.quadraticCurveTo(cx - .16 * s, vy + .02 * s, cx - .30 * s, vy - .07 * s); c.stroke();
  }
  c.restore();
  if (withBark) drawBarkSwatch(c, size * .14, size * 1.12, size * .72, size * .14, species);
  const url = cv.toDataURL(); iconCache[key] = url; return url;
}

/* Silhouette icon: same botanical path, near-black fill — the mastery clue tier. */
export function getTreeSilhouette(species: string, size: number): string {
  const key = `sil:${species}:${size}`;
  if (iconCache[key]) return iconCache[key];
  const cv = document.createElement('canvas');
  cv.width = size; cv.height = Math.round(size * 1.08);
  const c = cv.getContext('2d')!;
  const pathFn = LEAF_PATH[species] || LEAF_PATH['meşe'];
  pathFn(c, size / 2, size * .5, size * .86);
  c.fillStyle = '#233a33'; c.fill();
  const url = cv.toDataURL(); iconCache[key] = url; return url;
}

/* Bark-only clue: species bark texture as a large swatch. */
export function getBarkClue(species: string, size: number): string {
  const key = `bark:${species}:${size}`;
  if (iconCache[key]) return iconCache[key];
  const cv = document.createElement('canvas');
  cv.width = size; cv.height = size;
  const c = cv.getContext('2d')!;
  drawBarkSwatch(c, 0, 0, size, size, species);
  const url = cv.toDataURL(); iconCache[key] = url; return url;
}

export type ClueKind = 'leaf' | 'bark' | 'silhouette';

/* Art resolver — REAL PHOTOS FIRST (the mandated card art), vector fallback. */
export function getTreeArt(id: string, kind: ClueKind, size: number): string {
  const photos = photoFor(id);
  if (photos) {
    if (kind === 'leaf' && photos.leaf) return photos.leaf;
    if (kind === 'bark' && photos.bark) return photos.bark;
    if (kind === 'silhouette' && photos.tree) return photos.tree;
  }
  if (kind === 'bark') return getBarkClue(id, size);
  if (kind === 'silhouette') return getTreeSilhouette(id, size);
  return getTreeIcon(id, size, false);
}
/* Choice-card art (leaf + bark strip, or photo). */
export function getChoiceArt(id: string, size: number): string {
  const photos = photoFor(id);
  if (photos?.leaf) return photos.leaf;
  return getTreeIcon(id, size, true);
}
